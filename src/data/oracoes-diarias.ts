/** Seleciona a oração do dia com offset diferente do versículo e passagem */
export function getOracaoDoDia(): OracaoDiaria {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 1);
  const dayOfYear = Math.floor((now.getTime() - start.getTime()) / 86400000);
  // Offset de 7 para não coincidir com os outros
  return ORACOES_DIARIAS[(dayOfYear + 7) % ORACOES_DIARIAS.length];
}
